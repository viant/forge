import fs from 'node:fs';
import {createRequire} from 'node:module';
import nodePath from 'node:path';
const inputRoot=process.argv[2];
if(!inputRoot) throw new Error('Pass a folder containing npm-installed d3-geo@3.1.1, topojson-client@3.1.0, world-atlas@2.0.2, i18n-iso-countries@7.14.0, and topojson-simplify@3.0.3');
const require=createRequire(nodePath.resolve(inputRoot,'package.json'));
const {geoNaturalEarth1,geoPath}=await import(require.resolve('d3-geo'));
const {feature}=require('topojson-client');
const countries=require('i18n-iso-countries');
const {presimplify,quantile,simplify}=require('topojson-simplify');
const topology=JSON.parse(fs.readFileSync(require.resolve('world-atlas/countries-50m.json')));
const weighted=presimplify(topology);
const simplified=simplify(weighted,quantile(weighted,.8));
const features=feature(simplified,simplified.objects.countries).features.filter(f=>f.properties.name!=='Antarctica');
const projection=geoNaturalEarth1().fitExtent([[8,8],[952,492]],{type:'FeatureCollection',features});
const path=geoPath(projection).digits(1);
const paths=features.map(f=>{const iso2=countries.numericToAlpha2(f.id)||(f.properties.name==='Kosovo'?'XK':'');const iso3=iso2?countries.alpha2ToAlpha3(iso2):'';return {key:iso2||f.properties.name.toUpperCase(),label:f.properties.name,aliases:[f.properties.name.toUpperCase(),f.id,iso2,iso3].filter(Boolean),path:path(f),center:path.centroid(f).map(v=>Math.round(v*10)/10),small:Math.max(...path.bounds(f)[1].map((v,i)=>v-path.bounds(f)[0][i]))<5};});
fs.writeFileSync(new URL('../src/components/dashboard/worldCountryPaths.js',import.meta.url),'// Generated from world-atlas 2.0.2 / Natural Earth 50m, ISC license.\n// Projection: d3-geo Natural Earth; ISO aliases: i18n-iso-countries 7.14.0.\nexport const WORLD_COUNTRY_PATHS = '+JSON.stringify(paths)+';\n');
console.log('Generated '+paths.length+' country paths.');
