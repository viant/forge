// Metadata-only timings for a supplied private definition, never a public fixture.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { performance } from 'node:perf_hooks';
import { createHash } from 'node:crypto';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { stringify } from 'yaml';
import { readDocument, sharedSourceAtPath, sharedSourceIndex, mutateDocument } from '../src/window-editor/windowDocument';
import { buildWindowTree, indexTree, visibleTreeRows, revealTreePath } from '../src/window-editor/treeInteraction';
import WindowYamlEditor from '../src/window-editor/WindowYamlEditor';
import { documentJSON } from '../src/window-editor/documentJSON';
import { canonicalBundleMetadata, loadBundleCanonicalizer } from '../src/window-editor/bundleCanonical';
await import('../public/window-editor/wasm_exec.js');
const input=process.argv[2], label=process.argv[3]||'profile';
const raw=await fs.readFile(input), definition=JSON.parse(raw);
const source=process.argv[4]?createRequire(import.meta.url)(process.argv[4]).formatDefinitionYAML(definition):stringify(definition,{indent:2,lineWidth:0,aliasDuplicateObjects:false});
const stages={};
const time=(name,action)=>{const start=performance.now();const result=action();stages[name]=Math.round((performance.now()-start)*100)/100;return result;};
const parsed=time('parse',()=>readDocument(source));
if(parsed.errors.length)throw new Error(parsed.errors.join(';'));
const roots=time('tree',()=>buildWindowTree(parsed.value));
const index=time('index',()=>indexTree(roots));
const initialIndexNodes=index.size;
const expanded=new Set(['group:web','group:ios','group:android','variant:web:0']);
const rows=time('visible',()=>visibleTreeRows(roots,expanded));
const key=definition.targets[0].variant;
time('reveal',()=>revealTreePath(['variants',key,'window','dataSource'],roots));
const shared=time('sharedSourceIndex',()=>sharedSourceIndex(parsed.document));
time('sharedSource25',()=>{for(let i=0;i<25;i++)sharedSourceAtPath(parsed.document,['variants',key,'window'],shared);});
time('renderTree',()=>renderToStaticMarkup(React.createElement(WindowYamlEditor,{defaultValue:source,readOnly:true})));
const wasm=await fs.readFile(new URL('../public/window-editor/canonical.wasm',import.meta.url));
const fetchBefore=globalThis.fetch;
globalThis.fetch=async()=>({ok:true,arrayBuffer:async()=>wasm.buffer.slice(wasm.byteOffset,wasm.byteOffset+wasm.byteLength)});
await loadBundleCanonicalizer(new URL('http://private-profile.invalid/'));
globalThis.fetch=fetchBefore;
const json=time('preciseCSTJSON',()=>documentJSON(parsed.document));
const result=time('canonicalWasm',()=>canonicalBundleMetadata(source,undefined,parsed.document));
const mutation=time('mutateAndCanonicalize',()=>mutateDocument(parsed.document,['variants',key,'window','chipName'],'private profile title'));
const edited=readDocument(mutation);
time('editedStateValidation',()=>canonicalBundleMetadata(mutation,undefined,edited.document));
time('undoCachedValidation',()=>canonicalBundleMetadata(source,undefined,parsed.document));
let baselineCanonicalEquivalence=null,editedBaselineEquivalence=null;
if(process.argv[5]) {
  const beforeGo=new globalThis.Go();
  const beforeBinary=await fs.readFile(process.argv[5]);
  const baseline=await WebAssembly.instantiate(beforeBinary,beforeGo.importObject);
  const currentAdapter=globalThis.forgeWindowCanonicalize;
  beforeGo.run(baseline.instance);
  const beforeAdapter=globalThis.forgeWindowCanonicalize;
  const expected=beforeAdapter(source);assert.ok(!expected.error);
  assert.deepEqual(result,JSON.parse(expected.result));
  const expectedEdited=beforeAdapter(mutation);assert.ok(!expectedEdited.error);
  assert.deepEqual(canonicalBundleMetadata(mutation,currentAdapter),JSON.parse(expectedEdited.result));
  baselineCanonicalEquivalence=editedBaselineEquivalence=true;
  globalThis.forgeWindowCanonicalize=currentAdapter;
}
const receipt={label,definitionSHA256:createHash('sha256').update(raw).digest('hex'),sourceBytes:Buffer.byteLength(source),targets:definition.targets.length,variants:Object.keys(definition.variants).length,initialIndexNodes,indexNodes:index.size,visibleNodes:rows.length,timingsMs:stages,preciseJSONAvailable:json!==null,canonicalMetadataSHA256:createHash('sha256').update(JSON.stringify(result)).digest('hex'),canonicalError:result.error||null,baselineCanonicalEquivalence,editedBaselineEquivalence,mutationBytes:Buffer.byteLength(mutation),environment:{node:process.version,platform:process.platform},limits:'One Node profiling sample. SSR/tree timings do not measure browser rendering or responsiveness.'};
await fs.writeFile(`output/window-editor/performance/${label}.json`,JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt,null,2));process.exit(0);
