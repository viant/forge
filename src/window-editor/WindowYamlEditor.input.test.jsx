import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><html><body><div id="test"></div></body></html>', { url: 'http://localhost', pretendToBeVisual: true });
for (const key of ['window','document','navigator','HTMLElement','MutationObserver','Window','Document','Node','Range','DOMRect','getComputedStyle','requestAnimationFrame','cancelAnimationFrame']) Object.defineProperty(globalThis, key, { value: dom.window[key], configurable: true });
// jsdom has no text layout; geometry is tested separately in the real browser.
window.Range.prototype.getClientRects = () => [];
window.Range.prototype.getBoundingClientRect = () => new window.DOMRect();
const browserErrors = [];
window.addEventListener('error',(event) => { browserErrors.push(event.error || event.message); event.preventDefault(); });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const React = await import('react');
const { act } = React;
const { createRoot } = await import('react-dom/client');
const { default: WindowYamlEditor } = await import('./WindowYamlEditor');
const root = createRoot(document.getElementById('test'));
let changed = [];
const source = 'title: Original\ncount: 2\nflag: false\nchoice: one\n';
const schema = { type: 'object', properties: {title:{type:'string'},count:{type:'integer'},flag:{type:'boolean'},choice:{type:'string',enum:['one','two']}} };
await act(() => root.render(<WindowYamlEditor defaultValue={source} schema={schema} onChange={(next) => changed.push(next)} />));
const field = (name) => document.querySelector(`[aria-label="${name}"]`) || [...document.querySelectorAll('label')].find((label) => label.textContent === name)?.control;
const input = async (name, value) => { const control = field(name); await act(() => { const setter = Object.getOwnPropertyDescriptor(control.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype, 'value').set; setter.call(control, value); control.dispatchEvent(new window.Event(control.tagName === 'SELECT' ? 'change' : 'input', {bubbles:true})); }); };
const blur = async (name) => act(() => field(name).dispatchEvent(new window.FocusEvent('focusout', {bubbles:true})));
assert.equal(document.querySelector('[role="treeitem"][tabindex="0"]').getAttribute('aria-label'), 'Document root');
for (const text of ['O','Or','Original changed']) { await input('title',text); assert.equal(document.querySelector('.fwe-pending'),null,'active typing never introduces pending banner'); }
await blur('title'); assert.match(changed.at(-1),/title: Original changed/); assert.equal(document.querySelector('.fwe-pending'),null);
await input('title','temporary'); await input('title','Original changed'); await blur('title'); assert.equal(document.querySelector('.fwe-pending'),null,'restored text clears draft');
await input('count','abc'); await blur('count'); assert.equal(field('count').getAttribute('aria-invalid'),'true'); assert.ok(document.querySelector('.fwe-pending')); assert.match(changed.at(-1),/count: 2/);
await act(() => [...document.querySelectorAll('button')].find((button) => button.textContent === 'YAML').click());
await act(() => [...document.querySelectorAll('button')].find((button) => button.textContent === 'Tree').click());
assert.equal(field('count').value,'abc');
await input('count','3'); await blur('count'); assert.match(changed.at(-1),/count: 3/); assert.equal(document.querySelector('.fwe-pending'),null);
await input('flag','true'); assert.match(changed.at(-1),/flag: true/);
await input('choice','two'); assert.match(changed.at(-1),/choice: two/);
// The real Go runtime exercises draft cleanup and path ownership after rekeying.
await import('../../public/window-editor/wasm_exec.js');
const fs = await import('node:fs/promises');
const go = new globalThis.Go();
const { instance } = await WebAssembly.instantiate(await fs.readFile(new URL('../../public/window-editor/canonical.wasm', import.meta.url)), go.importObject);
go.run(instance);
const { sample } = await import('./demoSample');
const { readDocument, rekeyBundle } = await import('./windowDocument');
const bundleDocument = readDocument(sample).document; rekeyBundle(bundleDocument);
await act(() => root.render(<WindowYamlEditor key="bundle" defaultValue={bundleDocument.toString()} onChange={(next) => changed.push(next)} />));
const click = async (text) => act(() => [...document.querySelectorAll('button')].find((button) => button.textContent === text).click());
await click('window');
const navigate = async (name) => act(() => document.querySelector(`button[aria-label="${name}"]`).click());
await navigate('Edit view: 2 attributes'); await navigate('Edit content: 8 attributes');
await input('title','A canonical title'); await blur('title');
assert.equal(document.querySelector('.fwe-pending'),null);
await click('YAML'); assert.equal(document.querySelector('.fwe-pending'),null,'rekeyed committed drafts cannot reappear in YAML mode'); await click('Tree');
assert.equal(document.querySelector('[role="treeitem"][aria-selected="true"]').getAttribute('aria-label'),'content · A canonical title');
assert.equal(document.querySelector('[role="treeitem"][aria-selected="true"] button.fwe-node').title, 'content · A canonical title');
assert.match(document.querySelector('.fwe-path').title,/variants \/ [a-f0-9]{64}/);
const add = document.querySelector('.fwe-add select');
await act(() => { add.value='rowSpan'; add.dispatchEvent(new window.Event('change',{bubbles:true})); }); await click('Add attribute');
await input('rowSpan','abc'); await blur('rowSpan');
await input('title','Another title'); await blur('title');
assert.equal(field('rowSpan').value,'abc','uncommitted draft follows renamed variant');
await input('rowSpan','0'); await blur('rowSpan');
assert.equal(document.querySelector('.fwe-pending'),null);

await act(() => root.render(<><WindowYamlEditor value={source} schema={schema} showHeader={false} /><WindowYamlEditor defaultValue={source} headingLevel={3} /></>));
assert.equal(document.querySelectorAll('main').length,0); assert.equal(document.querySelectorAll('h1').length,0); assert.equal(document.querySelectorAll('.fwe-title').length,1); assert.equal(document.querySelectorAll('header').length,1);
assert.ok(document.querySelector('h3.fwe-heading'));
const ids = [...document.querySelectorAll('[id]')].map((node) => node.id); assert.equal(new Set(ids).size, ids.length,'two editors have unique control IDs');
await act(() => root.render(<WindowYamlEditor key="aliases" defaultValue={'base: &desktop\n  title: Shared\nphone: *desktop\n'} />));
assert.ok(document.querySelector('.fwe-shared'),'tree identifies aliases and shared anchors');
await navigate('Edit phone: 1 attributes');
assert.match(document.querySelector('.fwe-shared-notice').textContent,/edits update anchor &desktop and all its aliases/);
assert.ok([...document.querySelectorAll('.fwe-shared-notice button')].some((button) => button.textContent === 'Go to anchor desktop'));
await act(() => root.unmount());
console.log('Rendered bundle rekey/draft ownership, input commit, restored draft, numeric error/recovery, mode retention, boolean/enum and embedding tests passed.');
assert.deepEqual(browserErrors, [], "component test must not emit browser errors");
process.exit(0);
