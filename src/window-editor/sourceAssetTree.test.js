import assert from 'node:assert/strict';
import {sourceAssetNodes, sourceAssetAncestors, visibleSourceAssets, sourceAssetKey} from './sourceAssetTreeModel.js';
const paths = ['extension/forge/windows/ad/shared/main.yaml', 'extension/forge/windows/ad/main.yaml', 'extension/forge/windows/hooks.js', 'extension/forge/styles/base.css'];
const nodes = sourceAssetNodes(paths);
const expanded = new Set(paths.flatMap(sourceAssetAncestors));
const rows = visibleSourceAssets(nodes, expanded);
assert.deepEqual(rows.filter(n => n.kind === 'file').map(n => n.path).sort(), [...paths].sort());
assert.equal(sourceAssetNodes([...paths, paths[0]])[0].children.length, 1);
assert.equal(rows.find(n => n.path === paths[0]).level, 6);
const folder = 'folder:extension/forge/windows/ad';
let result = sourceAssetKey('ArrowLeft', folder, rows, expanded);
assert.equal(result.expanded.has(folder), false);
assert.equal(visibleSourceAssets(nodes, result.expanded).some(n => n.path === paths[0]), false);
result = sourceAssetKey('ArrowRight', folder, visibleSourceAssets(nodes, result.expanded), result.expanded);
assert.equal(result.expanded.has(folder), true);
result = sourceAssetKey('ArrowRight', folder, rows, expanded);
assert.equal(result.focus, 'folder:extension/forge/windows/ad/shared');
assert.equal(sourceAssetKey('ArrowLeft', result.focus, rows, new Set()).focus, folder);
const file = `file:${paths[0]}`;
assert.equal(sourceAssetKey('Enter', file, rows, expanded).selected, paths[0]);
assert.equal(sourceAssetKey(' ', file, rows, expanded).selected, paths[0]);
assert.equal(sourceAssetKey('Home', file, rows, expanded).focus, rows[0].id);
assert.equal(sourceAssetKey('End', file, rows, expanded).focus, rows.at(-1).id);
assert.equal(sourceAssetKey('ArrowUp', rows[0].id, rows, expanded).focus, rows[0].id);
assert.equal(sourceAssetKey('ArrowDown', rows.at(-1).id, rows, expanded).focus, rows.at(-1).id);
assert.equal(sourceAssetKey('Escape', file, rows, expanded), null);
assert.deepEqual(sourceAssetNodes([]), []);
assert.equal(sourceAssetNodes(['a file/a.b.yaml'])[0].children[0].path, 'a file/a.b.yaml');
console.log('Source asset paths, folders, selection and keyboard navigation passed.');
