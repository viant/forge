import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import '../../public/window-editor/wasm_exec.js';
import { sample } from './demoSample';
import { readDocument, rekeyBundle, mutateDocument, removeDocumentNode, sharedSourceAtPath, schemaAtPath } from './windowDocument';
const go = new globalThis.Go();
const {instance} = await WebAssembly.instantiate(await fs.readFile(new URL('../../public/window-editor/canonical.wasm',import.meta.url)),go.importObject);
go.run(instance);
const document = readDocument(sample).document;
rekeyBundle(document);
let source = document.toString({lineWidth:0});
let parsed = readDocument(source);
assert.ok(parsed.value.targets[0].target.platform === '');
assert.ok(parsed.value.targets.every((target) => /^[a-f0-9]{64}$/.test(target.variant)));
await fs.mkdir('output/window-editor/fable-fixes',{recursive:true});
await fs.writeFile('output/window-editor/fable-fixes/demo-initial.yaml',source);
const key = parsed.value.targets[2].variant;
source = mutateDocument(parsed.document,['variants',key,'window','view','content','title'],'Edited phone');
parsed = readDocument(source);
const editedKey = parsed.value.targets[2].variant;
assert.notEqual(editedKey,key);
assert.equal(parsed.value.variants[editedKey].window.view.content.title,'Edited phone');
assert.ok(!parsed.value.variants[key]);
assert.match(source,/Custom attributes/);
assert.ok(parsed.value.variants[editedKey].window.view.content.customExtension);
await fs.writeFile('output/window-editor/fable-fixes/demo-edited.yaml',source);
source = mutateDocument(parsed.document,['variants',editedKey,'dataSources','records','backend','rows'],[{precise:'9007199254740993'}]);
// Inject a precise YAML numeric token; the Go adapter receives source bytes.
source = source.replace('precise: "9007199254740993"','precise: 9007199254740993').replace("precise: '9007199254740993'",'precise: 9007199254740993');
parsed = readDocument(source); rekeyBundle(parsed.document); source=parsed.document.toString({lineWidth:0});
assert.match(source,/precise: 9007199254740993/);
source = source.replace('precise: 9007199254740993', 'precise: 9007199254740993\n              decimal: 1.234567890123456789');
parsed = readDocument(source); rekeyBundle(parsed.document); source = parsed.document.toString({lineWidth:0});
assert.match(source,/decimal: 1\.234567890123456789/);
parsed = readDocument(source);
assert.throws(() => removeDocumentNode(parsed.document, ['variants',parsed.value.targets[2].variant,'window','view','content']), /invalid complete window variant/);

await fs.writeFile('output/window-editor/fable-fixes/demo-descriptor-edited.yaml',source);
const alias = readDocument('base: &desktop\n  title: Shared\nphone: *desktop\n');
assert.deepEqual(sharedSourceAtPath(alias.document,['phone','title']),{anchor:'desktop',anchorPath:['base'],alias:true});
assert.equal(sharedSourceAtPath(alias.document,['base','title']).anchor,'desktop');
assert.ok(schemaAtPath(['variants',editedKey,'dataSources','records','backend'],parsed.value).properties.kind,'bundle datasource uses committed canonical descriptor model');
console.log('Exact Go bundle fingerprints, descriptor dependencies, source precision, extension preservation and shared-source metadata passed.');
process.exit(0);
