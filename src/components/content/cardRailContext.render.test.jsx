import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import React, {act} from 'react';
import {createRoot} from 'react-dom/client';
import CardRail from './CardRail.jsx';
import CardRailGroup from './CardRailGroup.jsx';
import {getViewSignal} from '../../core/store/signals.js';

const dom=new JSDOM('<!doctype html><html><body><div id="root"></div><button id="outside">Outside</button></body></html>',{url:'http://127.0.0.1/'});
globalThis.window=dom.window;globalThis.document=dom.window.document;globalThis.HTMLElement=dom.window.HTMLElement;
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
window.matchMedia=()=>({matches:true});
globalThis.ResizeObserver=class {observe(){} disconnect(){}};
const observers=[];
globalThis.IntersectionObserver=class {
    constructor(callback,options){this.callback=callback;this.root=options.root;this.targets=new Set();this.disconnected=false;observers.push(this);}
    observe(target){this.targets.add(target);}
    disconnect(){this.disconnected=true;}
    deliver(items){this.callback(items.map(([target,ratio])=>({target,isIntersecting:ratio>0,intersectionRatio:ratio})));}
};
const root=createRoot(document.getElementById('root'));
const render=async element=>act(async()=>root.render(element));
const context={identity:{windowId:'deals-window'}};
const otherContext={identity:{windowId:'another-window'}};
const signal=getViewSignal('deals-window');
signal.value={tabs:{workspace:'marketplace'},other:'preserved'};
const rows=[{id:81700,title:'HBO Max'},{id:55402,title:'A+E'},{id:999,title:'Another deal'}];
const current=()=>signal.peek().cardRails?.deals;
const observer=()=>observers.at(-1);
const cards=()=>[...document.querySelectorAll('.forge-content-card')];
let actions=0;
await render(<CardRail id="deals" context={context} value={rows} heading="Deals" onClick={()=>actions++}/>);
assert.deepEqual(current(),{title:'Deals',total:3},'Before measurement no card is guessed visible or selected');
assert.equal(observer().root,null,'Viewport measurement also respects clipping by the scrollable rail ancestor');
assert.equal(observer().targets.size,3);
await act(async()=>observer().deliver([[cards()[0],1],[cards()[1],0.4],[cards()[2],0]]));
assert.deepEqual(current().visibleItems,[{itemId:81700,title:'HBO Max',index:0},{itemId:55402,title:'A+E',index:1}]);
await act(async()=>observer().deliver(cards().map(card=>[card,0])));
assert.deepEqual(current().visibleItems,[],'Hidden retained rail or offscreen window publishes no visible cards');
await act(async()=>observer().deliver([[cards()[0],1],[cards()[1],0.4]]));
await act(async()=>{
    cards()[1].querySelector('button').focus();
    assert.deepEqual(current().focusedItem,{itemId:55402,title:'A+E',index:1},'Focus publishes synchronously before the next render');
});
assert.equal(actions,0,'Focusing and measuring cards never invokes business actions');
await act(async()=>cards()[1].querySelector('button').click());
assert.equal(actions,1,'Existing card open action still executes exactly once');
await act(async()=>document.getElementById('outside').focus());
assert.equal(current().focusedItem,undefined,'Leaving a card clears focused state');
assert.equal(current().visibleItems.length,2,'Blur preserves measured visibility');
const track=document.querySelector('[role=list]');
await act(async()=>{
    track.dispatchEvent(new window.Event('scroll',{bubbles:true}));
    observer().deliver([[cards()[0],0],[cards()[2],0.6]]);
});
assert.deepEqual(current().visibleItems.map(item=>item.itemId),[55402,999],'Scrolling updates intersection membership without selecting a card');
assert.equal(current().focusedItem,undefined);
await act(async()=>cards()[1].querySelector('button').focus());
const oldObserver=observer(),oldTargets=cards();
await render(<CardRail id="deals" context={context} value={[rows[2],{...rows[1],title:'A+E updated'},rows[0]]} heading="Deals"/>);
assert.equal(oldObserver.disconnected,true);
assert.deepEqual(current().focusedItem,{itemId:55402,title:'A+E updated',index:1},'Collection changes refresh the focused record');
assert.equal(current().visibleItems,undefined,'Old viewport measurements are omitted while the new collection is unmeasured');
await act(async()=>oldObserver.deliver([[oldTargets[0],1]]));
assert.equal(current().visibleItems,undefined,'Late observer callbacks cannot restore stale visibility');
await act(async()=>observer().deliver([[cards()[0],1],[cards()[1],1],[cards()[2],0]]));
assert.deepEqual(current().visibleItems.map(item=>item.itemId),[999,55402],'Visible records follow current collection order');
await render(<CardRail id="deals" context={context} value={[rows[1],rows[2]]} heading="Deals"/>);
assert.deepEqual(current().focusedItem,{itemId:55402,title:'A+E',index:0},'Reordering retains identity and refreshes index');
await render(<CardRail id="deals" context={context} value={[rows[2]]} heading="Deals"/>);
assert.equal(current().focusedItem,undefined,'Removing the focused card clears its identity');
assert.equal(current().visibleItems,undefined);
const many=Array.from({length:20},(_,index)=>({id:`deal-${index}`,title:`Deal ${index}`}));
await render(<CardRail id="deals" context={context} value={many} heading="Deals"/>);
await act(async()=>observer().deliver(cards().map(card=>[card,1])));
assert.equal(current().visibleItems.length,12,'Visible context stays bounded');
assert.deepEqual(current().visibleItems.map(item=>item.index),Array.from({length:12},(_,index)=>index));
await render(<CardRail id="deals" context={context} value={[{id:'x'.repeat(257),title:'t'.repeat(300)}]} heading={'h'.repeat(300)}/>);
await act(async()=>observer().deliver([[cards()[0],1]]));
assert.equal(current().title.length,240);
assert.equal(current().visibleItems[0].title.length,240);
assert.equal(current().visibleItems[0].itemId,undefined,'Oversized IDs are omitted instead of truncated into a different identity');
await render(<CardRail id="deals" context={context} value={[]} heading="Deals"/>);
assert.equal(current(),undefined,'Empty collection clears the rail entry');
await render(<><CardRail id="deals" context={context} value={rows}/><CardRail id="deals" context={otherContext} value={rows}/></>);
const firstObserver=observers.at(-2),secondObserver=observer();
await act(async()=>{
    firstObserver.deliver([[cards()[0],1]]);
    secondObserver.deliver([[cards()[4],1]]);
    cards()[0].querySelector('button').focus();
});
assert.equal(current().focusedItem.itemId,81700);
assert.equal(getViewSignal('another-window').peek().cardRails.deals.focusedItem,undefined);
assert.deepEqual(current().visibleItems.map(item=>item.itemId),[81700]);
assert.deepEqual(getViewSignal('another-window').peek().cardRails.deals.visibleItems.map(item=>item.itemId),[55402],'Same rail IDs in different windows remain independent');
await render(<div/>);
assert.equal(current(),undefined);
assert.equal(getViewSignal('another-window').peek().cardRails.deals,undefined);
assert.deepEqual(signal.peek().tabs,{workspace:'marketplace'});
assert.equal(signal.peek().other,'preserved','Rail lifecycle preserves unrelated view state');
await render(<CardRailGroup id="market" context={context} value={[{id:'premium',heading:'Premium',value:rows},{id:'other',heading:'Other',value:[rows[2]]}]}/>);
assert.deepEqual(Object.keys(signal.peek().cardRails).sort(),['market-other','market-premium'],'Groups forward instance context to distinct section rails');
await act(async()=>observers.at(-2).deliver([[cards()[0],1]]));
assert.equal(signal.peek().cardRails['market-premium'].visibleItems[0].itemId,81700);
await render(<div/>);
delete globalThis.IntersectionObserver;
await render(<CardRail id="deals" context={context} value={rows}/>);
assert.deepEqual(current(),{title:'',total:3},'Unavailable viewport measurement never claims visible items');
await act(async()=>root.unmount());
assert.equal(current(),undefined);
dom.window.close();
console.log('Card rail viewport, focus, collection reconciliation and scoped context pass');
