import React from 'react';
import {act, create} from 'react-test-renderer';
import assert from 'node:assert/strict';
import EditableTextCell from './EditableTextCell.jsx';
import {shouldSelectRowForCellAction} from './cellActionSelection.js';
let view, changes=[];
act(()=>{view=create(<EditableTextCell value="Original" label="Name 42" maxLength={255} onChange={event=>changes.push(event.target.value)}/>);});
const input=()=>view.root.findByType('input');
assert.equal(input().props['aria-label'],'Name 42');
assert.equal(input().props.maxLength,255);
let stopped=0;
act(()=>input().props.onChange({target:{value:'Edited'},stopPropagation(){stopped++;}}));
assert.equal(input().props.value,'Edited');assert.deepEqual(changes,['Edited']);assert.equal(stopped,1);
input().props.onKeyDown({key:'Tab',stopPropagation(){stopped++;}});
input().props.onClick({stopPropagation(){stopped++;}});assert.equal(stopped,3);
act(()=>view.update(<EditableTextCell value="Saved" label="Name 42" onChange={event=>changes.push(event.target.value)}/>));
assert.equal(input().props.value,'Saved');
act(()=>view.update(<EditableTextCell value="Saved" label="Name 42" readOnly onChange={event=>changes.push(event.target.value)}/>));
assert.equal(input().props.readOnly,true);assert.equal(input().props.disabled,false);
act(()=>input().props.onChange({target:{value:'Forbidden'},stopPropagation(){}}));assert.deepEqual(changes,['Edited']);assert.equal(input().props.value,'Saved');
assert.equal(shouldSelectRowForCellAction({col:{type:'editableText'}},false),false);
assert.equal(shouldSelectRowForCellAction({col:{type:'link'}},false),true);
act(()=>view.unmount());console.log('EditableTextCell renders typing, read-only, external reset and keyboard isolation correctly.');
const {default:TableCell}=await import('./TableCell.jsx');
let received, rowClicks=0;
const row={id:42,name:'Current'},col={id:'name',name:'Name',type:'editableText',cellProperties:{'aria-label':'Custom row name'}};
const context={handlers:{dataSource:{isSelected:()=>false}}};
const changeHandler={isDefined:()=>true,execute:args=>{received=args;}};
act(()=>{view=create(<TableCell context={context} cell={{value:'Current',displayedText:'Current'}} cellSelection={{row,col}} columnHandlers={{onChange:changeHandler}} onRowClick={()=>rowClicks++}/>);});
act(()=>view.root.findByType('input').props.onChange({target:{value:'New'},stopPropagation(){}}));
assert.equal(received.row,row);assert.equal(received.col,col);assert.equal(received.context,context);assert.equal(received.event.target.value,'New');assert.equal(rowClicks,0);assert.equal(view.root.findByType('input').props['aria-label'],'Custom row name');
act(()=>view.update(<TableCell context={context} cell={{value:'Current',displayedText:'Current'}} cellSelection={{row,col}} columnHandlers={{onChange:changeHandler,onReadonly:{isDefined:()=>true,execute:()=>true}}}/>));
assert.equal(view.root.findByType('input').props.readOnly,true);assert.equal(view.root.findByType('input').props.disabled,false);
act(()=>view.unmount());console.log('TableCell forwards row/context/column/change and honors row read-only without selecting rows.');
