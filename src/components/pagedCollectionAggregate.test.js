import assert from 'node:assert/strict';
import {collectPagedCollection} from './pagedCollectionAggregate.js';
const rows = Array.from({length: 61}, (_, index) => ({id: index + 1}));
const calls = [];
const fetchPage = async page => {calls.push(page);return {data: rows.slice((page - 1) * 25, page * 25)};};
const options = {pageSize: 25, maxPages: 5, fetchPage, extractPage: payload => ({records: payload.data}), keyForRow: row => row.id};
const result = await collectPagedCollection(options);
assert.deepEqual(calls, [1, 2, 3]);
assert.deepEqual(result.records, rows);
assert.equal(result.info.totalCount, 61);
assert.equal(result.info.hasNext, false);
assert.equal(result.pages, 3);
const exactCalls = [];
const exact = await collectPagedCollection({...options, fetchPage: async page => {exactCalls.push(page);return {data: rows.slice(0, 50).slice((page - 1) * 25, page * 25)};}, maxPages: 3});
assert.equal(exact.records.length, 50);
assert.deepEqual(exactCalls, [1, 2, 3], 'an exact multiple needs one empty continuation probe');
await assert.rejects(collectPagedCollection({...options, fetchPage: async page => ({data: page === 1 ? rows.slice(0, 25) : [{id: 1}, ...rows.slice(25, 49)]}), maxPages: 3}), /duplicate/);
await assert.rejects(collectPagedCollection({...options, fetchPage: async page => page === 2 ? Promise.reject(new Error('page two failed')) : fetchPage(page)}), /page two failed/);
await assert.rejects(collectPagedCollection({...options, maxPages: 2}), /exceeded its 2-page bound/);
assert.equal((await collectPagedCollection({...options, fetchPage: async page => ({data: rows.slice((page - 1) * 25, page * 25), meta: {cnt: 61}}), extractPage: payload => ({records: payload.data, info: {totalCount: payload.meta.cnt}})})).pages, 3);
console.log('bounded aggregate paging preserves complete rows and fails closed');
